"""`tower admin nats-users`: move the bus from the shared token to per-producer users. Idempotent; dry run by default.

    tower admin nats-users plan                 what apply would change (paths, users, ACLs; never values)
    tower admin nats-users apply [--execute]    back up, create missing password files, write auth.conf
    tower admin nats-users switch-clients [--execute]   client.json mode user (run after the nats restart)
    tower admin nats-users rollback [--execute] restore the newest token auth.conf backup, client.json mode token
    tower admin nats-users verify [--stage s1|s2]   the window checks, in order

Without --execute, apply and rollback only print their plan. Nothing here restarts a service: each prints the restart
order. Paths are under TOWER_HOME (default ~/.tower): nats/{nats.conf,auth.conf,client.json}, nats/backup-<ts>/,
secrets/{tower,docket,nod-publisher}.password. Passwords are random, written straight to 0600 files and never
printed; auth.conf holds only bcrypt hashes, made with `nats server passwd` (the password goes in through the
PASSWORD environment variable, not the command line; TOWER_NATS_CLI overrides the binary).
"""

from __future__ import annotations

import json
import os
import re
import secrets
import shutil
import subprocess
import time
from dataclasses import dataclass
from pathlib import Path

MARKER = "# generated by tower admin nats-users"


@dataclass(frozen=True)
class User:
    name: str
    password_name: str
    publish: tuple[str, ...] = ()     # () with subscribe () means all permissions
    subscribe: tuple[str, ...] = ()


USERS = (
    User("tower", "tower.password"),
    User("docket", "docket.password", ("ev.docket.>", "ev.lead.>"), ("_INBOX_docket.>",)),
    User("nod", "nod-publisher.password", ("ev.nod.>",), ("_INBOX_nod.>",)),
)


class UsersError(Exception):
    pass


@dataclass
class Paths:
    home: Path

    @classmethod
    def from_env(cls, home: str | None = None) -> "Paths":
        return cls(Path(os.path.expanduser(home or os.environ.get("TOWER_HOME") or "~/.tower")))

    @property
    def nats(self) -> Path:
        return self.home / "nats"

    @property
    def secrets(self) -> Path:
        return self.home / "secrets"

    @property
    def conf(self) -> Path:
        return self.nats / "nats.conf"

    @property
    def auth(self) -> Path:
        return self.nats / "auth.conf"

    @property
    def client(self) -> Path:
        return self.nats / "client.json"

    def password(self, user: User) -> Path:
        return self.secrets / user.password_name

    def backups(self) -> list[Path]:
        return sorted(self.nats.glob("backup-*"), reverse=True)


RESTART_APPLY = """Next, in order (nothing was restarted):
  1. nats-server -c {conf} -t                         check the config
  2. fleet restart nats                               token clients are refused from here on
  3. tower admin nats-users switch-clients --execute  client.json mode user
  4. fleet restart tower-host                         reconnects as user tower
  5. Docket: user docket, {docket}, inbox prefix _INBOX_docket (Docket lead)
  6. tower admin nats-users verify --stage s1; one Docket fire lands on TOWER
  Nod (S2, later): user nod, {nod}, inbox prefix _INBOX_nod (Nod lead)"""

RESTART_ROLLBACK = """Restart order (nothing was restarted):
  1. nats-server -c {conf} -t
  2. fleet restart nats                       token auth again; user clients are refused
  3. fleet restart tower-host                 reconnects with the token (client.json mode token)
  4. Docket and Nod back to their token settings, then restart them (their leads)"""


def acl(user: User) -> str:
    if not user.publish and not user.subscribe:
        return "all"
    return f"publish {', '.join(user.publish)}; subscribe {', '.join(user.subscribe)}"


def _is_generated(path: Path) -> bool:
    try:
        return path.read_text().startswith(MARKER)
    except OSError:
        return False


def _write_private(path: Path, text: str) -> None:
    """Atomic write, 0600 from the first byte."""
    path.parent.mkdir(parents=True, exist_ok=True, mode=0o700)
    tmp = path.with_name(f".{path.name}.tmp-{os.getpid()}")
    fd = os.open(tmp, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "w") as f:
        f.write(text)
    os.replace(tmp, path)


def _hash(password: str) -> str:
    binary = os.environ.get("TOWER_NATS_CLI") or "nats"
    try:
        result = subprocess.run([binary, "server", "passwd"], env={**os.environ, "PASSWORD": password},
                                capture_output=True, text=True, timeout=30)
    except (OSError, subprocess.TimeoutExpired) as exc:
        raise UsersError(f"nats server passwd failed ({exc.__class__.__name__})") from None
    digest = result.stdout.strip()
    if result.returncode != 0 or not digest.startswith("$2"):
        raise UsersError("nats server passwd did not return a bcrypt hash")
    return digest


def render_auth(hashes: dict[str, str]) -> str:
    lines = [MARKER + "; bcrypt hashes only, passwords live in the secrets files", "authorization {", "  users = ["]
    for user in USERS:
        entry = f'    {{user: "{user.name}", password: "{hashes[user.name]}"'
        if user.publish or user.subscribe:
            pub = ", ".join(f'"{s}"' for s in user.publish)
            sub = ", ".join(f'"{s}"' for s in user.subscribe)
            entry += f", permissions: {{publish: {{allow: [{pub}]}}, subscribe: {{allow: [{sub}]}}}}"
        lines.append(entry + "}")
    lines += ["  ]", "}", ""]
    return "\n".join(lines)


def plan(paths: Paths) -> list[str]:
    """What apply would do, as lines with no secret values."""
    out = []
    for path in (paths.conf, paths.auth):
        if not path.is_file():
            out.append(f"MISSING {path} (run scripts/setup-nats.sh first)")
    missing = [u for u in USERS if not paths.password(u).exists()]
    generated = _is_generated(paths.auth)
    rewrite = not generated or bool(missing)
    if rewrite:
        out.append(f"back up {paths.conf} and {paths.auth} to {paths.nats}/backup-<timestamp>/ (0600)")
    for user in USERS:
        state = "create (random, 0600, not printed)" if user in missing else "exists, keep"
        out.append(f"password file {paths.password(user)}: {state}")
    if rewrite:
        out.append(f"write {paths.auth} (bcrypt hashes only, 0600) with users:")
        out += [f"  {u.name}: {acl(u)}" for u in USERS]
    else:
        out.append(f"{paths.auth}: already per-user, unchanged")
    out.append(f"{paths.client}: not written by apply (switch-clients, after the nats restart)")
    return out


def client_pointer(paths: Paths) -> dict:
    return {"mode": "user", "user": "tower", "password_file": str(paths.password(USERS[0]))}


def switch_clients(paths: Paths, *, execute: bool = False) -> list[str]:
    """Point Tower clients at user tower. Only once auth.conf is per-user (after apply and the nats restart)."""
    if not _is_generated(paths.auth) or not paths.password(USERS[0]).exists():
        raise UsersError("auth.conf is not per-user yet: run apply --execute first")
    if _read_json(paths.client) == client_pointer(paths):
        return ["nothing to change" if execute else "DRY RUN (add --execute):",
                f"{paths.client}: already mode user, tower"]
    if not execute:
        return ["DRY RUN (add --execute):", f"{paths.client}: write mode user, user tower (0600)"]
    _write_private(paths.client, json.dumps(client_pointer(paths), indent=1) + "\n")
    return [f"wrote {paths.client} (mode user)", "", "Next: fleet restart tower-host, then verify --stage s1"]


def apply(paths: Paths, *, execute: bool = False) -> list[str]:
    lines = plan(paths)
    if any(line.startswith("MISSING") for line in lines):
        raise UsersError("nats.conf or auth.conf is missing")
    if not execute:
        return ["DRY RUN (add --execute):"] + lines
    missing = [u for u in USERS if not paths.password(u).exists()]
    rewrite = not _is_generated(paths.auth) or bool(missing)
    done = []
    if rewrite:
        backup = paths.nats / f"backup-{time.strftime('%Y%m%d-%H%M%S')}-{os.getpid()}"
        backup.mkdir(mode=0o700)
        for path in (paths.conf, paths.auth):
            shutil.copyfile(path, backup / path.name)
            os.chmod(backup / path.name, 0o600)
        done.append(f"backed up to {backup}")
    paths.secrets.mkdir(parents=True, exist_ok=True, mode=0o700)
    for user in missing:
        fd = os.open(paths.password(user), os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
        with os.fdopen(fd, "w") as f:
            f.write(secrets.token_urlsafe(32) + "\n")
        done.append(f"created {paths.password(user)}")
    if rewrite:
        hashes = {u.name: _hash(paths.password(u).read_text().strip()) for u in USERS}
        _write_private(paths.auth, render_auth(hashes))
        done.append(f"wrote {paths.auth} ({len(USERS)} users)")
    if not done:
        done.append("nothing to change")
    return done + ["", RESTART_APPLY.format(conf=paths.conf, docket=paths.password(USERS[1]),
                                            nod=paths.password(USERS[2]))]


def _token_backup(paths: Paths) -> Path | None:
    for backup in paths.backups():
        auth = backup / "auth.conf"
        if auth.is_file() and not _is_generated(auth):
            return auth
    return None


def rollback(paths: Paths, *, execute: bool = False) -> list[str]:
    source = _token_backup(paths)
    if source is None and _is_generated(paths.auth):
        raise UsersError("no token auth.conf backup to restore")
    lines = []
    if _is_generated(paths.auth):
        lines.append(f"restore {source} over {paths.auth} (current kept in {paths.nats}/rollback-<timestamp>/)")
    else:
        lines.append(f"{paths.auth}: already token auth, unchanged")
    current = _read_json(paths.client)
    lines.append(f"{paths.client}: " + ("unchanged (mode token)" if current == {"mode": "token"}
                                       else "write mode token"))
    lines.append("password files are kept")
    if not execute:
        return ["DRY RUN (add --execute):"] + lines
    done = []
    if _is_generated(paths.auth):
        keep = paths.nats / f"rollback-{time.strftime('%Y%m%d-%H%M%S')}-{os.getpid()}"
        keep.mkdir(mode=0o700)
        shutil.copyfile(paths.auth, keep / "auth.conf")
        os.chmod(keep / "auth.conf", 0o600)
        _write_private(paths.auth, source.read_text())
        done.append(f"restored {source} (per-user auth.conf kept in {keep})")
    if current != {"mode": "token"}:
        _write_private(paths.client, json.dumps({"mode": "token"}) + "\n")
        done.append(f"wrote {paths.client} (mode token)")
    if not done:
        done.append("nothing to change")
    return done + ["", RESTART_ROLLBACK.format(conf=paths.conf)]


def _read_json(path: Path):
    try:
        return json.loads(path.read_text())
    except (OSError, json.JSONDecodeError):
        return None


# -- verify (read-only checks, in order) ------------------------------------------------


def configured_users(paths: Paths) -> list[str]:
    """User names in auth.conf (as generated by apply)."""
    try:
        text = paths.auth.read_text()
    except OSError:
        return []
    return sorted(re.findall(r'\{user: "([^"]+)"', text))


async def verify(paths: Paths, stage: str = "s1", *, url: str | None = None,
                 monitor: str = "http://127.0.0.1:8222") -> list[tuple[str, bool, str]]:
    """The window checks, in the recorded order; stops at the first failure. Returns (check, ok, detail).

    Docket may be absent (its publisher connects per publish); its proof is one Docket fire landing on TOWER.
    Before S2 the nod user must not be active.
    """
    import asyncio
    import urllib.request

    import nats

    from . import bus

    if stage not in ("s1", "s2"):
        raise UsersError("stage must be s1 or s2")
    url = url or os.environ.get("TOWER_NATS_URL") or bus.DEFAULT_URL
    results: list[tuple[str, bool, str]] = []

    def done(check: str, ok: bool, detail: str) -> bool:
        results.append((check, ok, detail))
        return ok

    # 1. Configured users are exactly tower, docket and nod.
    names, want = configured_users(paths), sorted(u.name for u in USERS)
    if not done("configured users", names == want, f"{','.join(names) or '-'} (expected {','.join(want)})"):
        return results

    # 2. The shared token is refused.
    token = bus.read_token(str(paths.secrets / "nats.token"))
    if token is None:
        ok = done("token refused", True, "no token file")
    else:
        try:
            nc = await asyncio.wait_for(nats.connect(url, token=token, allow_reconnect=False,
                                                     max_reconnect_attempts=0, connect_timeout=3,
                                                     error_cb=_quiet), 10)
            await nc.close()
            ok = done("token refused", False, "a token connection was accepted")
        except Exception as exc:  # noqa: BLE001
            # Only a real authorization denial proves the token is refused; anything else is unknown.
            if is_auth_denial(exc):
                ok = done("token refused", True, "Authorization Violation")
            else:
                ok = done("token refused", False, f"unknown: {exc.__class__.__name__} (not an authorization denial)")
    if not ok:
        return results

    # 3. Tower's client.json works: connect as user tower and read the stream.
    try:
        nc = await bus.connect(url, client_config=str(paths.client), allow_reconnect=False,
                               max_reconnect_attempts=0)
        try:
            info = await nc.jetstream().stream_info(bus.STREAM)
            ok = done("tower via client.json", True, f"stream {bus.STREAM} {info.state.messages} msgs")
        finally:
            await nc.close()
    except Exception as exc:  # noqa: BLE001
        ok = done("tower via client.json", False, exc.__class__.__name__)
    if not ok:
        return results

    # 4. Active connections (ours above is closed): tower active, nod not before S2, docket optional,
    #    nobody else and no connection without a user.
    try:
        with urllib.request.urlopen(f"{monitor.rstrip('/')}/connz?auth=1&limit=1024", timeout=5) as response:
            conns = json.load(response).get("connections") or []
    except Exception as exc:  # noqa: BLE001
        done("active users", False, f"monitor unreadable ({exc.__class__.__name__})")
        return results
    active = sorted({c.get("authorized_user") for c in conns if c.get("authorized_user")})
    anonymous = sum(1 for c in conns if not c.get("authorized_user"))
    allowed = {"tower", "docket"} | ({"nod"} if stage == "s2" else set())
    problems = []
    if "tower" not in active:
        problems.append("tower not active")
    if stage == "s1" and "nod" in active:
        problems.append("nod active before S2")
    if set(active) - allowed - {"nod"}:
        problems.append("unexpected users")
    if anonymous:
        problems.append(f"{anonymous} without a user")
    done("active users", not problems,
         f"{','.join(active) or '-'} active, {len(conns)} connections" + (f": {'; '.join(problems)}" if problems else ""))
    return results


def is_auth_denial(exc: BaseException) -> bool:
    """True only for NATS refusing the credentials: AuthorizationError, or the plain nats.errors.Error that nats-py
    raises for the server's -ERR 'Authorization Violation'. Timeouts, resets and OSErrors are not."""
    import nats.errors

    if isinstance(exc, nats.errors.AuthorizationError):
        return True
    return type(exc) is nats.errors.Error and "authorization violation" in str(exc).lower()


async def _quiet(exc: Exception) -> None:
    return None
